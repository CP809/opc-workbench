def main():
    with io.open("knowledge.json", encoding="utf-8") as f:
        kb = json.load(f)
    for key, items in (("ai", AI), ("cs", CS)):
        exist = {x.get("term") for x in kb.get(key, [])}
        n = 0
        for term, explain in items:
            if term not in exist:
                kb.setdefault(key, []).append({"term": term, "explain": explain})
                n += 1
        print(key, "+", n, "→", len(kb[key]))
    with io.open("knowledge.json", "w", encoding="utf-8") as f:
        json.dump(kb, f, ensure_ascii=False, indent=2)


if __name__ == "__main__":
    main()
